"""Tables for Phase 3 (python -m lsbfd.novel report). Reads <out>/ml and <out>/cnn."""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

BASELINES = [("Logistic regression, pdm-bench (Phase 1)", "0.508 (single run)"),
             ("1D CNN, pdm-bench (Phase 1, 50 epochs)", "0.436 ± 0.023"),
             ("ERM CNN, Phase 2 trainer (20 epochs)", "0.404 ± 0.027")]
REF = "lr / generic"  # paired comparisons are against the baseline's features in our pipeline


def load(out: Path) -> pd.DataFrame:
    rows = []
    for p in sorted((out / "ml").glob("fold*/*.json")):
        r = json.loads(p.read_text())
        rows.append({"fold": r["fold"], "method": f"{r['model']} / {r['feature_set']}",
                     "seed": r["seed"], "macro_f1": r["metrics"]["macro_f1"],
                     "bal_acc": r["metrics"]["balanced_accuracy"],
                     "per_bearing": r["metrics"]["per_bearing_accuracy"],
                     "held_out": " ".join(r["held_out"])})
    for p in sorted((out / "cnn").glob("fold*/*.json")):
        r = json.loads(p.read_text())
        for mode, m in r["metrics"].items():
            name = {"none": "env-CNN (DG)", "adabn_pooled": "env-CNN + AdaBN pooled (TTA)",
                    "adabn_per_bearing": "env-CNN + AdaBN per bearing (TTA)"}[mode]
            rows.append({"fold": r["fold"], "method": name, "seed": r["seed"],
                         "macro_f1": m["macro_f1"], "bal_acc": m["balanced_accuracy"],
                         "per_bearing": m["per_bearing_accuracy"],
                         "held_out": " ".join(r["held_out"])})
    return pd.DataFrame(rows)


def _ms(x: pd.Series) -> str:
    return f"{x.mean():.3f}" if len(x) == 1 else f"{x.mean():.3f} ± {x.std(ddof=1):.3f}"


def report(out: Path) -> str:
    df = load(out)
    if df.empty:
        return f"No Phase 3 results under {out}\n"
    lines = ["# Phase 3 tables (generated by `python -m lsbfd.novel report`)", "",
             "## Benchmark split (fold 0: K001, KA30, KB23, KI21)", "",
             "| Method | Runs | Macro-F1 | Balanced acc. | K001 | KA30 | KB23 | KI21 |",
             "|---|---|---|---|---|---|---|---|"]
    for name, v in BASELINES:
        lines.append(f"| {name} | | {v} | | | | | |")
    f0 = df[df.fold == 0]
    for method, g in f0.groupby("method", sort=False):
        pb = pd.DataFrame(list(g.per_bearing)).mean()
        lines.append(f"| {method} | {len(g)} | {_ms(g.macro_f1)} | {_ms(g.bal_acc)} | "
                     + " | ".join(f"{pb.get(b, float('nan')):.2f}"
                                  for b in ("K001", "KA30", "KB23", "KI21")) + " |")
    # rotated folds: one value per fold (seeds averaged), paired against the reference
    per_fold = df.groupby(["method", "fold"]).macro_f1.mean().unstack("fold")
    n_folds = per_fold.notna().sum(axis=1)
    if n_folds.max() > 1:
        lines += ["", f"## All folds (benchmark split + rotated hold-outs; one value per fold, "
                  "seeds averaged)", "",
                  f"Paired against `{REF}` on the same folds. p is a two-sided Wilcoxon "
                  "signed-rank test over folds.", "",
                  "| Method | Folds | Macro-F1 mean ± std | Min | Δ vs ref (mean) | Folds better | p |",
                  "|---|---|---|---|---|---|---|"]
        from scipy.stats import wilcoxon

        ref = per_fold.loc[REF] if REF in per_fold.index else None
        for method, row in per_fold.iterrows():
            v = row.dropna()
            if len(v) < 2:
                continue
            cells = [method, str(len(v)), f"{v.mean():.3f} ± {v.std(ddof=1):.3f}", f"{v.min():.3f}"]
            if ref is not None and method != REF:
                common = v.index.intersection(ref.dropna().index)
                d = v[common] - ref[common]
                p = wilcoxon(d).pvalue if len(d) >= 5 and np.any(d != 0) else float("nan")
                cells += [f"{d.mean():+.3f}", f"{int((d > 0).sum())} of {len(d)}", f"{p:.3f}"]
            else:
                cells += ["—", "—", "—"]
            lines.append("| " + " | ".join(cells) + " |")
        held = df.drop_duplicates("fold").sort_values("fold")[["fold", "held_out"]]
        lines += ["", "Held-out bearings per fold: "
                  + "; ".join(f"{int(f)}: {h}" for f, h in held.itertuples(index=False))]
    return "\n".join(lines) + "\n"
