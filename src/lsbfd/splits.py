"""Resolve the benchmark's train/test splits from file names and check them for leakage.

Only file paths are read, never signals, so this runs in seconds even for all of PU.
Metadata columns mirror what pdm-bench's loaders produce, so the scenario queries in
pdm-bench's `config/task/*.yaml` select exactly the same recordings.

Usage:
    python -m lsbfd.splits                 # all six scenarios
    python -m lsbfd.splits pu_cross_bearing_instance
Writes results/splits/<scenario>.csv (plus leakage_report.md when all scenarios run), and exits
non-zero if any recording appears in both train and test.
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parents[2]
TASK_DIR = ROOT / "third_party" / "pdm-bench" / "config" / "task"
CWRU_DIR = "datasets/javadseraj-cwru-bearing-fault-data-set/Datasets/CWRU"
PU_DIR = "datasets/paderborn-university-bearing-dataset"

SCENARIOS = [
    "cwru_cross_load",
    "cwru_cross_fs",
    "cwru_cross_fault_instance",
    "pu_cross_operating_condition",
    "pu_cross_damage_provenance",
    "pu_cross_bearing_instance",
]


def pu_meta(root: Path) -> pd.DataFrame:
    """One row per PU file (HostService raster), with pdm-bench's PU metadata."""
    from pdm_bench.loaders.pu import (
        _infer_damage_provenance,
        _infer_label_from_bearing_code,
        _parse_pu_filename,
    )

    rows = []
    for f in sorted((root / PU_DIR).rglob("*.mat")):
        info = _parse_pu_filename(f.stem)
        group_id = f"{info['setting_id']}/{info['bearing_code']}/{info['measurement_no']}"
        rows.append(
            {
                "id": f"{group_id}::HostService",
                "raster": "HostService",
                "group_id": group_id,
                "label": _infer_label_from_bearing_code(info["bearing_code"]),
                "damage_provenance": _infer_damage_provenance(info["bearing_code"]),
                "operating_condition": info["operating_condition"],
                "bearing_code": info["bearing_code"],
                # One physical bearing per PU bearing code.
                "physical_bearing": info["bearing_code"],
            }
        )
    return pd.DataFrame(rows)


def cwru_meta(root: Path) -> pd.DataFrame:
    """One row per CWRU drive-end recording, with pdm-bench's CWRU metadata."""
    from pdm_bench.loaders.cwru import _infer_fs, _normalize_label, _parse_fault_family

    base = root / CWRU_DIR
    rows = []
    for f in sorted(base.rglob("*.mat")):
        experiment, rpm = f.parent.relative_to(base).parts
        family = _parse_fault_family(f.stem)
        rows.append(
            {
                "id": f"{experiment}/{rpm}/{f.stem}",
                "Experiment": experiment,
                "rpm": float(rpm),
                "fs": _infer_fs(f),
                "label": _normalize_label(f.stem),
                **family,
                # CWRU seeded each fault (size + location) on one bearing and recorded it
                # at all four loads, so the fault family identifies the physical bearing.
                # Fan-end faults sit on a different bearing from drive-end faults.
                "physical_bearing": ("FE:" if "FanEnd" in experiment else "DE:")
                + family["recording_family"],
            }
        )
    return pd.DataFrame(rows)


def load_queries(scenario: str) -> tuple[str, str]:
    cfg = yaml.safe_load((TASK_DIR / f"{scenario}.yaml").read_text())
    return cfg["dataset"]["train_query"], cfg["dataset"]["test_query"]


def resolve(scenario: str, root: Path) -> pd.DataFrame:
    """Return all recordings of the scenario's dataset with a 'split' column."""
    meta = pu_meta(root) if scenario.startswith("pu_") else cwru_meta(root)
    if meta.empty:
        raise FileNotFoundError(f"No .mat files found for {scenario} under {root}")
    train_q, test_q = load_queries(scenario)
    train = meta.query(train_q).assign(split="train")
    test = meta.query(test_q).assign(split="test")
    return pd.concat([train, test], ignore_index=True)


def check(df: pd.DataFrame) -> dict[str, list[str]]:
    """Identifiers present on both sides of the split, per level."""
    train, test = df[df.split == "train"], df[df.split == "test"]
    levels = {"recording": "id", "physical bearing": "physical_bearing"}
    if "group_id" in df:
        levels["measurement"] = "group_id"
    return {
        level: sorted(set(train[col]) & set(test[col])) for level, col in levels.items()
    }


def main(argv: list[str]) -> int:
    root = Path(os.environ.get("WORKSPACE", ROOT / "data" / "raw"))
    out = ROOT / "results" / "splits"
    out.mkdir(parents=True, exist_ok=True)
    scenarios = argv or SCENARIOS
    lines = [
        "# Leakage report",
        "",
        "Generated by `python -m lsbfd.splits`. A recording shared by train and test is a",
        "hard failure. A shared physical bearing is reported, not failed: some scenarios",
        "test generalisation to new conditions of the same bearings by design.",
        "",
        "| Scenario | Train rec. | Test rec. | Train classes | Test classes "
        "| Shared recordings | Shared physical bearings |",
        "|---|---|---|---|---|---|---|",
    ]
    failed = False
    for sc in scenarios:
        df = resolve(sc, root)
        df.to_csv(out / f"{sc}.csv", index=False)
        overlap = check(df)
        failed |= bool(overlap["recording"])
        tr, te = df[df.split == "train"], df[df.split == "test"]
        shared = overlap["physical bearing"]
        lines.append(
            f"| {sc} | {len(tr)} | {len(te)} | {', '.join(sorted(tr.label.unique()))} "
            f"| {', '.join(sorted(te.label.unique()))} | {len(overlap['recording'])} "
            f"| {len(shared)}{' (' + ', '.join(shared) + ')' if shared else ''} |"
        )
        print(f"{sc}: train={len(tr)} test={len(te)} "
              f"shared_recordings={len(overlap['recording'])} shared_bearings={len(shared)}")
    if scenarios == SCENARIOS:
        (out / "leakage_report.md").write_text("\n".join(lines) + "\n")
        print(f"Wrote {out / 'leakage_report.md'}")
    if failed:
        print("FAIL: at least one recording is in both train and test", file=sys.stderr)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
